"""Core domain value objects.

These Pydantic models are the contracts exchanged between subsystems and
are the single source of truth for the API schemas, the agent tool
signatures and the provenance payloads.

Design rules enforced here:

* Every assertion carries an :class:`AssertionClass` so observed fact,
  inference and recommendation are never conflated.
* Evidence is content-addressed: the payload lives off-chain, the
  ``evidence_hash`` is what the ledger commits to.
* Risk results are structured, explained and carry uncertainty.
* No model stores real patient identifiers; patient context is synthetic
  and explicitly labelled as such.
"""

