class EvidenceRef(DomainModel):
    """Content-addressed evidence reference.

    The payload is kept off-chain (``payload`` here, persisted in the
    evidence store). Only ``evidence_hash`` plus metadata is committed to
    the permissioned ledger, which is what keeps raw telemetry and
    synthetic patient context off the blockchain.
    """

    evidence_id: str
    kind: EvidenceKind
    created_at: datetime
    assertion_class: AssertionClass = AssertionClass.OBSERVED_FACT
    produced_by: str = Field(description="Subsystem or agent that produced this evidence")
    summary: str = ""
    event_ids: list[str] = Field(default_factory=list)
    payload: dict[str, Any] = Field(default_factory=dict)
    evidence_hash: str = ""

    def with_hash(self) -> EvidenceRef:
        """Return a copy with ``evidence_hash`` computed over the payload."""
        digest = canonical_hash(
            {
                "evidence_id": self.evidence_id,
                "kind": self.kind.value,
                "event_ids": sorted(self.event_ids),
                "payload": self.payload,
            }
        )
        return self.model_copy(update={"evidence_hash": digest})

    def verify(self) -> bool:
        """Re-derive the digest and compare. Backs ``verifyEvidence``."""
        return bool(self.evidence_hash) and self.with_hash().evidence_hash == self.evidence_hash


