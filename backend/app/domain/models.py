class ProvenanceRecord(DomainModel):
    """A record committed to the permissioned ledger.

    Deliberately small: identifiers, hashes, verdicts and timestamps only.
    Raw telemetry, logs, synthetic patient context and model artefacts stay
    off-chain and are referenced by hash.
    """

    provenance_id: str
    event_type: ProvenanceEventType
    incident_id: str
    device_id: str | None = None
    timestamp: datetime
    evidence_hash: str = ""
    detector_result_hash: str | None = None
    risk_summary: dict[str, float] = Field(default_factory=dict)
    agent_decision: str | None = None
    recommended_action: str | None = None
    approval_status: str | None = None
    approver: str | None = None
    executed_action: str | None = None
    execution_result: str | None = None
    recovery_result: str | None = None
    policy_version: str | None = None
    formulation_version: str | None = None
    submitting_org: str = "SecurityOpsMSP"

    def payload_for_ledger(self) -> dict[str, Any]:
        """Canonical, minimal dict actually written to the ledger."""
        data = self.model_dump(mode="json", exclude_none=True)
        for forbidden in ("payload", "patient", "telemetry"):
            data.pop(forbidden, None)
        return data


