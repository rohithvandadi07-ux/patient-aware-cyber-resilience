class NormalisedEvent(DomainModel):
    """A single normalised event from the event/telemetry layer.

    One schema for telemetry, network flows, device state, commands, auth and
    security logs, so the detection pipeline and the benchmark-dataset
    loaders can share feature extraction.
    """

    event_id: str
    timestamp: datetime
    kind: EventKind
    device_id: str | None = None
    source_ip: str | None = None
    destination_ip: str | None = None
    source_mac: str | None = None
    protocol: str | None = None
    source_port: int | None = None
    destination_port: int | None = None
    # Numeric measurements: telemetry vitals, flow statistics, counters.
    measurements: dict[str, float] = Field(default_factory=dict)
    # Categorical / textual attributes: command names, auth results, flags.
    attributes: dict[str, str] = Field(default_factory=dict)
    # Simulator ground truth. Present ONLY for simulator- or dataset-sourced
    # events and never consumed by detection at inference time; used solely
    # for supervised training and evaluation.
    ground_truth_attack: AttackType | None = None
    ground_truth_is_attack: bool | None = None
    scenario_id: str | None = None

    def feature_view(self) -> dict[str, float | str | None]:
        """Flat view for feature extraction, excluding ground-truth labels."""
        out: dict[str, float | str | None] = {
            "kind": self.kind.value,
            "device_id": self.device_id,
            "protocol": self.protocol,
            "source_port": float(self.source_port) if self.source_port is not None else None,
            "destination_port": (
                float(self.destination_port) if self.destination_port is not None else None
            ),
        }
        for k, v in self.measurements.items():
            out[f"m_{k}"] = v
        for k, v in self.attributes.items():
            out[f"a_{k}"] = v
        return out


