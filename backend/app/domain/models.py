class Incident(DomainModel):
    """The aggregate the whole closed loop revolves around."""

    incident_id: str
    created_at: datetime
    updated_at: datetime
    state: IncidentState = IncidentState.DETECTED
    device_id: str | None = None
    attack_type: AttackType = AttackType.UNKNOWN
    confidence: float = Field(default=0.0, ge=0.0, le=1.0)
    severity: Severity = Severity.INFO
    detection: DetectionResult | None = None
    evidence: list[EvidenceRef] = Field(default_factory=list)
    timeline: list[IncidentTimelineEntry] = Field(default_factory=list)
    agent_runs: list[AgentRunRecord] = Field(default_factory=list)
    cyber_risk: CyberRiskResult | None = None
    clinical_risk: ClinicalRiskResult | None = None
    decision: PatientAwareDecision | None = None
    responses: list[ResponseRecord] = Field(default_factory=list)
    recoveries: list[RecoveryResult] = Field(default_factory=list)
    provenance_refs: list[LedgerReceipt] = Field(default_factory=list)
    reinvestigation_count: int = 0
    scenario_id: str | None = None
    resolved_at: datetime | None = None
    # Metrics captured for the resilience evaluation (MTTD / MTTR).
    attack_started_at: datetime | None = None
    detected_at: datetime | None = None

    @computed_field  # type: ignore[prop-decorator]
    @property
    def approval_status(self) -> ApprovalStatus:
        for r in reversed(self.responses):
            if r.approval is not None:
                return r.approval.status
        return ApprovalStatus.NOT_REQUIRED

    @computed_field  # type: ignore[prop-decorator]
    @property
    def latest_response(self) -> ResponseRecord | None:
        return self.responses[-1] if self.responses else None

    @computed_field  # type: ignore[prop-decorator]
    @property
    def latest_recovery(self) -> RecoveryResult | None:
        return self.recoveries[-1] if self.recoveries else None

    @computed_field  # type: ignore[prop-decorator]
    @property
    def detection_latency_seconds(self) -> float | None:
        if self.attack_started_at is None or self.detected_at is None:
            return None
        return (self.detected_at - self.attack_started_at).total_seconds()

    @computed_field  # type: ignore[prop-decorator]
    @property
    def time_to_resolution_seconds(self) -> float | None:
        if self.detected_at is None or self.resolved_at is None:
            return None
        return (self.resolved_at - self.detected_at).total_seconds()

    def evidence_bundle_hash(self) -> str:
        """Aggregate hash over all evidence, committed at incident creation."""
        return canonical_hash(sorted(e.evidence_hash for e in self.evidence))


