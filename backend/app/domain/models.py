class SyntheticPatientContext(DomainModel):
    """Synthetic patient dependency context.

    SAFETY: every field here is generated by the simulator. No real patient
    identifiers, records or PHI are present or supported anywhere in this
    platform.
    """

    synthetic: Literal[True] = True
    patient_ref: str = Field(description="Synthetic opaque reference, e.g. 'SYN-PT-001'")
    acuity: AcuityLevel = AcuityLevel.STABLE
    dependency: PatientDependencyLevel = PatientDependencyLevel.NONE
    on_life_support: bool = False
    clinician_present: bool = True
    # Minutes of device interruption judged clinically tolerable in the
    # simulation. Drives the clinical-risk term; never a clinical guideline.
    tolerable_interruption_minutes: float = Field(default=30.0, ge=0.0)

    @field_validator("patient_ref")
    @classmethod
    def _must_be_synthetic_ref(cls, v: str) -> str:
        if not v.upper().startswith("SYN-"):
            raise ValueError("patient_ref must be a synthetic reference prefixed 'SYN-'")
        return v


