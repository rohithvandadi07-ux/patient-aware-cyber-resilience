class RiskFactor(DomainModel):
    """One explained contribution to a risk score."""

    name: str
    value: float
    weight: float
    contribution: float
    rationale: str = ""
    assertion_class: AssertionClass = AssertionClass.OBSERVED_FACT


def _band(score: float) -> RiskBand:
    if score < 0.15:
        return RiskBand.NEGLIGIBLE
    if score < 0.35:
        return RiskBand.LOW
    if score < 0.60:
        return RiskBand.MODERATE
    if score < 0.82:
        return RiskBand.HIGH
    return RiskBand.SEVERE


class CyberRiskResult(DomainModel):
    score: float = Field(ge=0.0, le=1.0)
    factors: list[RiskFactor] = Field(default_factory=list)
    uncertainty: float = Field(default=0.0, ge=0.0, le=1.0)
    explanation: str = ""
    formulation_version: str = "v1"

    @computed_field  # type: ignore[prop-decorator]
    @property
    def band(self) -> RiskBand:
        return _band(self.score)


class ClinicalRiskResult(DomainModel):
    score: float = Field(ge=0.0, le=1.0)
    factors: list[RiskFactor] = Field(default_factory=list)
    uncertainty: float = Field(default=0.0, ge=0.0, le=1.0)
    explanation: str = ""
    formulation_version: str = "v1"
    # Surfaced separately because the policy engine hard-gates on these.
    life_support_involved: bool = False
    patient_dependency: PatientDependencyLevel = PatientDependencyLevel.NONE

    @computed_field  # type: ignore[prop-decorator]
    @property
    def band(self) -> RiskBand:
        return _band(self.score)


class ResponseImpactResult(DomainModel):
    """Impact assessment of ONE candidate response action."""

    action_type: ResponseActionType
    security_benefit: float = Field(ge=0.0, le=1.0)
    clinical_impact: float = Field(ge=0.0, le=1.0)
    service_interruption_seconds: float = Field(default=0.0, ge=0.0)
    reversible: bool = True
    backup_available: bool = False
    impact_class: ImpactClass = ImpactClass.LOW
    factors: list[RiskFactor] = Field(default_factory=list)
    explanation: str = ""
    formulation_version: str = "v1"

    @computed_field  # type: ignore[prop-decorator]
    @property
    def net_benefit(self) -> float:
        """Security gained minus clinical cost. Diagnostic, not the decision."""
        return round(self.security_benefit - self.clinical_impact, 6)


class PatientAwareDecision(DomainModel):
    """The central research artefact: the dual-risk decision record.

    This object is what makes the contribution auditable. It records the
    cyber risk, the clinical risk, the impact of every candidate considered,
    the chosen action, the deterministic rationale, and the counterfactual
    (what a cyber-risk-only defender would have chosen) so the trade-off is
    measurable rather than asserted.
    """

    incident_id: str
    decided_at: datetime
    cyber_risk: CyberRiskResult
    clinical_risk: ClinicalRiskResult
    candidate_impacts: list[ResponseImpactResult] = Field(default_factory=list)
    selected_action: ResponseActionType = ResponseActionType.MONITOR_ONLY
    decision_score: float = Field(default=0.0, description="Score of the selected candidate")
    decision_band: RiskBand = RiskBand.LOW
    rationale: str = ""
    # Counterfactual: the action a security-only policy would have taken.
    cyber_only_action: ResponseActionType | None = None
    diverged_from_cyber_only: bool = False
    divergence_reason: str = ""
    formulation_version: str = "v1"
    engine: Literal["deterministic"] = "deterministic"
    assertion_class: AssertionClass = AssertionClass.RECOMMENDATION


